import { mkdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { setupIngest, type IngestHarness } from "../../test/helpers/ingest.js";
import { detectMappings, loadOrDetectMappings } from "./autodetect.js";
import { ingestDropzone } from "./ingest.js";
import { MAPPINGS_FILE, MappingError } from "./mapping.js";

let h: IngestHarness;
let drop: string;
beforeEach(async () => {
  h = await setupIngest();
  drop = join(h.dir, "data", "imports");
  await rm(join(h.dir, MAPPINGS_FILE)); // a live workspace that has no mapping yet
});
afterEach(async () => {
  await h.cleanup();
});

describe("detectMappings on real-shaped exports", () => {
  it("recognizes Meta, Google (title rows, day-first dates) and GA4, and says why the JSON CRM was skipped", async () => {
    const d = await detectMappings(drop, "SAR");
    expect([...d.sources].sort()).toEqual(["google_ads", "meta_ads", "web_analytics"]);
    const by = Object.fromEntries(d.mappings!.sources.map((s) => [s.id, s]));
    expect(by.google_ads).toMatchObject({ skip_rows: 2, date_format: "dmy", file: "google-ads-*.csv", columns: { spend: "Cost", adset: "Ad group", impressions: "Impr." } });
    expect(by.meta_ads).toMatchObject({ skip_rows: 0, date_format: "iso", currency: "SAR", columns: { spend: "Amount spent (SAR)", conversions: "Results" } });
    expect(d.mappings!.attribution.source_aliases).toMatchObject({ meta: expect.arrayContaining(["facebook"]), google: expect.arrayContaining(["adwords"]) });
    expect(d.unmatched.map((u) => u.file)).toContain("crm-contacts-2026-10-17.json");
    expect(d.unmatched.find((u) => u.file.endsWith(".json"))!.reason).toMatch(/hand-written mapping/);
  });

  it("reads the exports with the generated mapping: no errors, same facts as the hand-written one for the ad platforms", async () => {
    const handWritten = await ingestDropzone({ ...h.deps });
    const hand = Object.fromEntries(handWritten.files.map((f) => [f.mapping_id, f.rows]));
    const { mappings } = await loadOrDetectMappings(h.dir, drop, "SAR");
    const fresh = await setupIngest();
    try {
      const report = await ingestDropzone({ ...fresh.deps, mappings });
      const auto = Object.fromEntries(report.files.map((f) => [f.mapping_id, f.rows]));
      expect(report.files.flatMap((f) => f.issues.filter((i) => i.severity === "error"))).toEqual([]);
      expect(auto.meta_ads).toBe(hand.meta_ads);
      expect(auto.google_ads).toBe(hand.google_ads);
      expect(auto.web_analytics).toBe(hand.ga4);
    } finally {
      await fresh.cleanup();
    }
  });
});

describe("loadOrDetectMappings", () => {
  it("writes the file once, then just reads it", async () => {
    const first = await loadOrDetectMappings(h.dir, drop, "SAR");
    expect(first.generated?.sources).toContain("meta_ads");
    expect(await readFile(join(h.dir, MAPPINGS_FILE), "utf8")).toMatch(/^# Generated by Medjay/);
    const second = await loadOrDetectMappings(h.dir, drop, "SAR");
    expect(second.generated).toBeNull();
    expect(second.mappings.sources.map((s) => s.id)).toEqual(first.mappings.sources.map((s) => s.id));
  });

  it("never overwrites a mapping a person wrote", async () => {
    await writeFile(join(h.dir, MAPPINGS_FILE), "version: 1\nsources: []\n", "utf8");
    await expect(loadOrDetectMappings(h.dir, drop, "SAR")).rejects.toThrow(MappingError);
    expect(await readFile(join(h.dir, MAPPINGS_FILE), "utf8")).toBe("version: 1\nsources: []\n");
  });

  it("lists the headers it found when nothing matches, and writes nothing", async () => {
    const empty = join(h.dir, "other-drop");
    await mkdir(empty);
    await writeFile(join(empty, "weird.csv"), "Foo,Bar,Baz\n1,2,3\n", "utf8");
    await expect(loadOrDetectMappings(h.dir, empty, "SAR")).rejects.toThrow(/weird\.csv \(headers: Foo, Bar, Baz\)/);
    await expect(stat(join(h.dir, MAPPINGS_FILE))).rejects.toThrow();
  });

  it("says so when the dropzone has no files", async () => {
    await expect(loadOrDetectMappings(h.dir, join(h.dir, "nowhere"), "SAR")).rejects.toThrow(/no CSV files found/);
  });
});

describe("what it refuses to guess", () => {
  const ads = (name: string, header: string, ...rows: string[]) => writeFile(join(drop, name), [header, ...rows].join("\n"), "utf8");
  beforeEach(async () => {
    for (const f of ["google-ads-2026-10-10_16.csv", "meta-ads-2026-10-10_16.csv", "ga4-landing-pages-2026-10-10_16.csv"]) await rm(join(drop, f));
  });

  it("an ad export with no platform in its name or headers", async () => {
    await ads("report.csv", "Day,Campaign,Cost", "2026-10-01,A,5");
    const d = await detectMappings(drop, "SAR");
    expect(d.sources).toEqual([]);
    expect(d.unmatched.find((u) => u.file === "report.csv")!.reason).toMatch(/not which platform/);
  });

  it("dates that could be day-first or month-first", async () => {
    await ads("meta-ads.csv", "Day,Campaign name,Amount spent,Impressions", "03/04/2026,A,5,100", "05/06/2026,A,5,100");
    const d = await detectMappings(drop, "SAR");
    expect(d.unmatched.find((u) => u.file === "meta-ads.csv")!.reason).toMatch(/day-first or month-first/);
  });

  it("takes month-first dates when a value proves it, and the currency from the base when the header has none", async () => {
    await ads("meta-ads.csv", "Day,Campaign name,Amount spent,Impressions", "10/25/2026,A,5,100", "10/26/2026,A,5,100");
    const d = await detectMappings(drop, "AED");
    expect(d.mappings!.sources[0]).toMatchObject({ date_format: "mdy", currency: "AED" });
  });

  it("maps CRM stage words it knows and reports the ones it does not", async () => {
    await ads("crm.csv", "Contact ID,Created At,Stage,UTM Source,UTM Campaign,Deal Value", "1,2026-10-01,New Lead,facebook,A,", "2,2026-10-02,Closed Won,facebook,A,900", "3,2026-10-03,Pending Docs,facebook,A,");
    const d = await detectMappings(drop, "SAR");
    expect(d.mappings!.sources[0]).toMatchObject({ kind: "crm", stage_map: { "New Lead": "lead", "Closed Won": "won" }, columns: { revenue: "Deal Value" } });
    expect(d.notes.join()).toMatch(/Pending Docs/);
  });

  it("reads a Respond.io style CRM export whose date column is called Created Date", async () => {
    await ads("respondio.csv", "Contact ID,Created Date,Stage,Deal Value,UTM Source,UTM Campaign,Phone", "1,2026-10-01,New Lead,,google,A,+966500000000");
    const d = await detectMappings(drop, "SAR");
    expect(d.mappings!.sources[0]).toMatchObject({ kind: "crm", columns: { created_at: "Created Date" } });
  });
});

describe("detectMappings on Google Ads summary exports (no date column)", () => {
  const put = (name: string, header: string, ...rows: string[]) => writeFile(join(drop, name), [header, ...rows].join("\n"), "utf8");
  beforeEach(async () => {
    for (const f of ["google-ads-2026-10-10_16.csv", "meta-ads-2026-10-10_16.csv", "ga4-landing-pages-2026-10-10_16.csv", "crm-contacts-2026-10-17.json"]) await rm(join(drop, f), { force: true });
    await put("Campaigns(2026.09.01-2026.09.30).csv", "Campaign Name,Campaign Group Name,Campaign Status,Cost,Conversions,Cost / conv.", 'georgia,,Enabled,"SAR8,450.00",78.00,SAR108.33');
    await put("Searches(Search_2026.09.01-2026.09.30).csv", "Search,Cost,Clicks,Impressions,Conversions", "thailand,SAR164.71,17,436,0.00");
    await put("Search_keywords(2026.09.01-2026.09.30).csv", "Search Keyword,Match type,Criterion Status,Campaign Status,Ad Group Status,Cost,Clicks,CTR", 'شهر عسل,Broad match,Enabled,Enabled,Enabled,"SAR3,059.91",288,9.77%');
    await put("Devices(2026.09.01-2026.09.30).csv", "Device,Cost,Clicks,Conversions", "Mobile phones,SAR29822.18,3226,345.00");
    await put("Time_series(2026.09.01-2026.09.30).csv", "Date,Conversions,Cost / conv.,Avg. CPC,Cost", '"Tue, Sep 1, 2026",14.00,SAR159.05,SAR8.10,"SAR2,226.72"');
  });

  it("maps each report by what its first column is, as a google ad_summary with the period left to the file name", async () => {
    const d = await detectMappings(drop, "SAR");
    expect(d.unmatched).toEqual([]);
    const by = Object.fromEntries(d.mappings!.sources.map((s) => [s.kind === "ad_summary" ? s.dimension : s.id, s]));
    expect(Object.keys(by).sort()).toEqual(["campaign", "day", "device", "keyword", "search_term"]);
    expect(by.campaign).toMatchObject({ kind: "ad_summary", platform: "google", currency: "SAR", file: "Campaigns(*).csv", columns: { key: "Campaign Name", spend: "Cost", conversions: "Conversions" } });
    expect(by.search_term).toMatchObject({ file: "Searches(Search_*).csv", columns: { key: "Search", spend: "Cost", clicks: "Clicks", impressions: "Impressions" } });
    expect(by.day).toMatchObject({ columns: { key: "Date", spend: "Cost" } });
  });

  it("ingests what it detected, end to end", async () => {
    const d = await detectMappings(drop, "SAR");
    const report = await ingestDropzone({ ...h.deps, mappings: d.mappings! });
    expect(report.files.filter((f) => f.status === "ingested")).toHaveLength(5);
    expect(h.store.database().prepare("SELECT COUNT(*) AS n FROM fact_period").get()).toEqual({ n: 5 });
  });

  it("leaves comparison reports, hour-of-day reports and Search Console files alone, and says why", async () => {
    await put("Biggest_changes(2026.09.01-2026.09.30_compared_to_2026.08.02-2026.08.31).csv", "Campaign Name,Cost,Cost (Comparison),Clicks,Clicks (Comparison)", "A,SAR10.00,SAR8.00,5,4");
    await put("Day_&_hour(Day_2026.09.01-2026.09.30).csv", "Day,Cost", "Monday,SAR50.00");
    await put("Queries.csv", "Top queries,Clicks,Impressions,CTR,Position", "x,1,2,3%,4");
    const d = await detectMappings(drop, "SAR");
    const reasons = Object.fromEntries(d.unmatched.map((u) => [u.file.slice(0, 12), u.reason]));
    expect(d.unmatched).toHaveLength(3);
    expect(reasons["Biggest_chan"]).toMatch(/comparison/i);
    expect(d.mappings!.sources).toHaveLength(5);
  });
});

describe("CRM stage words from Respond.io", () => {
  it("understands Unassigned, Follow Up and Quoted without a warning", async () => {
    await writeFile(join(drop, "crm.csv"), ["Contact ID,Created At,Stage,UTM Source,UTM Campaign,Deal Value", "1,2026-10-01,Unassigned,facebook,A,", "2,2026-10-02,Follow Up,facebook,A,", "3,2026-10-03,Quoted,facebook,A,"].join("\n"), "utf8");
    const d = await detectMappings(drop, "SAR");
    const crm = d.mappings!.sources.find((s) => s.kind === "crm");
    expect(crm).toMatchObject({ stage_map: { Unassigned: "lead", "Follow Up": "qualified", Quoted: "booked" } });
    expect(d.notes.join()).not.toMatch(/not recognized/);
  });
});
