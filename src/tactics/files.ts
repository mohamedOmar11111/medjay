// Tactics are plain Markdown files: tactics/<id>.md with YAML frontmatter (the state) and a free
// text playbook. A file that does not parse is reported, never silently skipped, and never rewritten.
import { mkdir, readdir, readFile, rename, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { parse as parseYaml, stringify } from "yaml";
import { TacticSchema, type Tactic } from "./schema.js";
import { TacticError } from "./state.js";

export const TACTICS_DIR = "tactics";
export const INDEX_FILE = "tested-tactics-log.md";

export interface TacticFile {
  tactic: Tactic;
  body: string;
  file: string;
}

export interface TacticProblem {
  file: string;
  message: string;
}

const FRONT = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/;

export function parseTacticFile(text: string): { tactic: Tactic; body: string } {
  const match = FRONT.exec(text.replace(/^﻿/, ""));
  if (!match) throw new TacticError("no frontmatter (expected --- ... --- at the top)");
  let raw: unknown;
  try {
    raw = parseYaml(match[1] as string);
  } catch (error) {
    throw new TacticError(`frontmatter is not valid YAML: ${error instanceof Error ? (error.message.split("\n")[0] ?? "") : String(error)}`);
  }
  const parsed = TacticSchema.safeParse(raw);
  if (!parsed.success) {
    throw new TacticError("tactic is invalid", parsed.error.issues.map((i) => ({ path: i.path.map(String).join("."), message: i.message })));
  }
  return { tactic: parsed.data, body: match[2] ?? "" };
}

export function serializeTactic(tactic: Tactic, body: string): string {
  const front = stringify(TacticSchema.parse(tactic), { lineWidth: 0 }).trimEnd();
  return `---\n${front}\n---\n${body.startsWith("\n") || body === "" ? body : `\n${body}`}`;
}

export async function loadTactics(workspaceDir: string): Promise<{ tactics: TacticFile[]; problems: TacticProblem[] }> {
  const dir = join(workspaceDir, TACTICS_DIR);
  let names: string[];
  try {
    names = await readdir(dir);
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return { tactics: [], problems: [] };
    throw error;
  }
  const tactics: TacticFile[] = [];
  const problems: TacticProblem[] = [];
  const seen = new Map<string, string>();
  for (const name of names.filter((n) => n.endsWith(".md") && n !== INDEX_FILE).sort()) {
    try {
      const { tactic, body } = parseTacticFile(await readFile(join(dir, name), "utf8"));
      if (name !== `${tactic.id}.md`) throw new TacticError(`the file is named ${name} but its id is ${tactic.id}; name it ${tactic.id}.md`);
      const earlier = seen.get(tactic.id);
      if (earlier) throw new TacticError(`id ${tactic.id} is already used by ${earlier}`);
      seen.set(tactic.id, name);
      tactics.push({ tactic, body, file: name });
    } catch (error) {
      problems.push({ file: name, message: error instanceof Error ? error.message : String(error) });
    }
  }
  return { tactics, problems };
}

/** Write a tactic atomically (temp file, then rename), so a crash never leaves half a file. */
export async function saveTactic(workspaceDir: string, tactic: Tactic, body: string): Promise<string> {
  const dir = join(workspaceDir, TACTICS_DIR);
  await mkdir(dir, { recursive: true });
  const name = `${tactic.id}.md`;
  const temp = join(dir, `.${name}.tmp`);
  await writeFile(temp, serializeTactic(tactic, body), "utf8");
  await rename(temp, join(dir, name));
  return name;
}

const row = (t: Tactic) => {
  const r = t.result;
  const evidence = r ? `effect ${(r.effect * 100).toFixed(0)}%, confidence ${r.confidence}, n=${r.sample_size}, ${r.outcome_source}${r.grading === "proxy" ? " (proxy)" : ""}` : t.experiment ? `${t.experiment.id}: ${t.experiment.metric}` : `${t.source.kind}: ${t.source.ref}`;
  return `| ${t.id} | ${t.title.replace(/\|/g, "/")} | ${t.tags.markets.join(", ") || "-"} | ${evidence.replace(/\|/g, "/")} |`;
};

/** The generated index (tested-tactics-log.md). The per-tactic files are the truth; this is a view. */
export function renderIndex(tactics: Tactic[]): string {
  const sections: [string, Tactic["state"], string][] = [
    ["Validated", "validated", "Worked in a pre-registered test, in the scope listed."],
    ["Hypothesized", "hypothesized", "A test is registered or running. Not proven."],
    ["Unverified", "unverified", "From a source, not yet tested here."],
    ["Invalidated (do not propose again)", "invalidated", "Tested here and did not work. Kept so the idea is not repeated."],
    ["Retired", "retired", "Was validated; contradicted or out of season."],
  ];
  const out = ["<!-- generated by `mdj tactic index`; edit the tactic files, not this table -->", "# Tested-tactics log", ""];
  for (const [title, state, note] of sections) {
    const list = tactics.filter((t) => t.state === state).sort((a, b) => a.id.localeCompare(b.id));
    out.push(`## ${title} (${list.length})`, "", note, "");
    if (list.length > 0) out.push("| Id | Tactic | Markets | Evidence |", "| --- | --- | --- | --- |", ...list.map(row), "");
  }
  return `${out.join("\n").trimEnd()}\n`;
}
