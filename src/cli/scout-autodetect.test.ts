import { execFile } from "node:child_process";
import { copyFile, mkdir, mkdtemp, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { promisify } from "node:util";
import { afterAll, beforeAll, describe, expect, it, vi } from "vitest";
import { verifyLedger } from "../audit/ledger.js";

vi.setConfig({ testTimeout: 180_000 });

const exec = promisify(execFile);
const REPO = join(import.meta.dirname, "..", "..");
const CLI = join(REPO, "dist", "cli.js"); // built once by test/global-setup.ts
const FIXTURE_DROP = join(REPO, "fixtures", "etlaala-ksa", "data", "imports");
let root: string;

async function mdj(...args: string[]): Promise<{ code: number; stdout: string; stderr: string }> {
  try {
    const { stdout, stderr } = await exec(process.execPath, [CLI, ...args], { cwd: REPO, timeout: 150_000 });
    return { code: 0, stdout, stderr };
  } catch (error) {
    const e = error as { code?: number; stdout?: string; stderr?: string };
    return { code: e.code ?? 1, stdout: e.stdout ?? "", stderr: e.stderr ?? "" };
  }
}

beforeAll(async () => {
  root = await mkdtemp(join(tmpdir(), "medjay-scout-auto-"));
});
afterAll(async () => {
  await rm(root, { recursive: true, force: true });
});

describe("mdj scout on a workspace with no ingestion.mappings.yaml", () => {
  it("mdj init does not need one, and scout writes it from the CSV headers", async () => {
    const ws = join(root, "live");
    await exec(process.execPath, [CLI, "init", ws, "--id", "live", "--currency", "SAR", "--business-type", "ecom"], { cwd: REPO });
    const drop = join(ws, "data", "imports");
    await mkdir(drop, { recursive: true });
    for (const f of ["meta-ads-2026-10-10_16.csv", "google-ads-2026-10-10_16.csv", "ga4-landing-pages-2026-10-10_16.csv"]) await copyFile(join(FIXTURE_DROP, f), join(drop, f));
    const r = await mdj("scout", "--workspace", ws, "--json");
    expect(r.code, r.stderr).toBe(0);
    expect(r.stderr).toMatch(/\[info\] Auto-generated ingestion\.mappings\.yaml from detected CSV headers/);
    expect(await readFile(join(ws, "ingestion.mappings.yaml"), "utf8")).toMatch(/meta_ads/);
    expect(await readFile(join(ws, ".medjay", "audit-log.jsonl"), "utf8")).toMatch(/ingest\.mappings_autogenerated/);
    expect((await verifyLedger(join(ws, ".medjay", "audit-log.jsonl"))).ok).toBe(true);
    const again = await mdj("scout", "--workspace", ws, "--json");
    expect(again.code, again.stderr).toBe(0);
    expect(again.stderr).not.toMatch(/Auto-generated/);
  });

  it("explains what it found when it cannot match anything, without crashing or writing a file", async () => {
    const ws = join(root, "odd");
    await exec(process.execPath, [CLI, "init", ws, "--id", "odd", "--business-type", "ecom"], { cwd: REPO });
    const drop = join(ws, "data", "imports");
    await mkdir(drop, { recursive: true });
    await (await import("node:fs/promises")).writeFile(join(drop, "mystery.csv"), "Foo,Bar\n1,2\n", "utf8");
    const r = await mdj("scout", "--workspace", ws);
    expect(r.code).toBe(1);
    expect(r.stderr).toMatch(/mystery\.csv \(headers: Foo, Bar\)/);
    await expect(readFile(join(ws, "ingestion.mappings.yaml"), "utf8")).rejects.toThrow();
  });
});
